#!/usr/bin/env python3
"""Write PredicateTheory/Generated.lean from ../cases.json.

Every case becomes Lean statements about its labels exactly as written
(`+num_gt(/x.num,"5")`), elaborated by the Lean declarations in `Elab.lean`
and decided by the proven checker:

  consistent: no       theorem  no world satisfies the literals   (consistent_dead)
  consistent: yes      theorem  a world does, and the expansion is exact (consistent_live)
  consistent: unknown  example  the checker says unknown
  entails g: yes       theorem  every world satisfying the premises passes the goal
  entails g: no        theorem  a countermodel exists              (entails_no)
  entails g: unknown   example  the checker says unknown
  runtime: no / yes    theorem  as above, with the case's accepted state known
  lint declaration-unparsed   example  the declaration does not parse

The only thing this script interprets is label syntax: name, sign, and
argument strings. Elaboration, typing, and every verdict are Lean's.

Run from this directory: python3 gen_cases.py
"""

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
CASES = HERE.parent / "cases.json"
OUT = HERE / "PredicateTheory" / "Generated.lean"

LITERAL = re.compile(r"^([+-])(\w+)(?:\((.*)\))?$")


def split_args(raw):
    args, cur, quoted = [], "", False
    for ch in raw:
        if ch == '"':
            quoted = not quoted
            cur += ch
        elif ch == "," and not quoted:
            args.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        args.append(cur.strip())
    return [a[1:-1] if len(a) >= 2 and a[0] == a[-1] == '"' else a for a in args]


def lean_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def label(text):
    m = LITERAL.match(text.strip())
    if not m:
        raise ValueError(f"not a label: {text}")
    sign, name, raw = m.groups()
    pos = "true" if sign == "+" else "false"
    if raw is None:
        return f"⟨{pos}, {lean_str(name)}, [], true⟩"
    args = ", ".join(lean_str(a) for a in split_args(raw))
    return f"⟨{pos}, {lean_str(name)}, [{args}], false⟩"


def labels(texts):
    return "[" + ", ".join(label(t) for t in texts) + "]"


def opt(s):
    return "none" if s is None else f"(some {lean_str(s)})"


def ident(case_id):
    return "case_" + re.sub(r"\W", "_", case_id)


def main():
    cases = json.loads(CASES.read_text())["cases"]
    lines = [
        "import PredicateTheory.Spec",
        "",
        "/-!",
        "Generated by `gen_cases.py` from `../cases.json`. Do not edit.",
        "",
        "Every case, as its labels are written, elaborated by the Lean",
        "declarations and decided by the proven checker. A `dead` or `live`",
        "verdict, an entailment, and a countermodel are theorems about every",
        "world (and every meaning of the opaque predicates); an `unknown` is a",
        "computed fact about the checker.",
        "-/",
        "",
        "namespace PredicateTheory",
        "",
        "set_option maxRecDepth 16384",
        "",
    ]
    counts = {"theorem": 0, "example": 0}

    def thm(name, stmt, proof):
        counts["theorem"] += 1
        lines.append(f"theorem {name} :")
        lines.append(f"    {stmt} :=")
        lines.append(f"  {proof}")

    def ex(stmt):
        counts["example"] += 1
        lines.append(f"example : {stmt} := by decide")

    for case in cases:
        cid = case["id"]
        name = ident(cid)
        v1 = case.get("v1", {})
        lines.append(f"/-! ### {cid}: {case['title']} -/")
        lines.append("")
        lines.append(f"def {name} : List Label := {labels(case['literals'])}")

        reg = "standard"
        decls = case.get("declarations")
        if decls:
            reg = f"{name}_reg"
            entries = ", ".join(
                f"({lean_str(m)}, Declaration.ofText {opt(d.get('necessary'))} {opt(d.get('sufficient'))})"
                for m, d in decls.items()
            )
            lines.append(f"def {reg} : Registry := registryWith [{entries}]")
            wants = "modality/declaration-unparsed" in case.get("lint", [])
            some_unparsed = " || ".join(
                f"(Declaration.ofText {opt(d.get('necessary'))} {opt(d.get('sufficient'))}).unparsed"
                for d in decls.values()
            )
            lines.append(f"-- lint modality/declaration-unparsed: {'yes' if wants else 'no'}")
            ex(f"({some_unparsed}) = {'true' if wants else 'false'}")
        lines.append("")

        exp = f"(expandAll {reg} {name})"
        want = v1.get("consistent")
        if want == "no":
            thm(f"{name}_dead", f"∀ I, ¬ Sat I {exp}.lits", "consistent_dead (by decide)")
        elif want == "yes":
            thm(f"{name}_live", f"{exp}.exact = true ∧ ∀ I, Sat I {exp}.lits",
                "consistent_live (by decide)")
        elif want == "unknown":
            ex(f"consistent {reg} {name} = .unknown")

        for i, (goal, answer) in enumerate(v1.get("entails", {}).items()):
            g = label(goal)
            lines.append(f"-- entails {goal}: {answer}")
            if answer == "yes":
                thm(f"{name}_entails_{i}", f"∀ I, LabelEntails I {reg} {name} {g}",
                    "entails_yes (by decide)")
            elif answer == "no":
                thm(f"{name}_countermodel_{i}",
                    f"∀ I, ∃ qs, goalQueries {reg} {g} = some qs ∧ ∃ q ∈ qs, Sat I ({exp}.lits ++ q)",
                    "entails_no (by decide)")
            else:
                ex(f"entailsV {reg} {name} {g} = .unknown")

        runtime = case.get("runtime")
        if runtime:
            state = ", ".join(
                f"({lean_str(k)}, {lean_str(v)})" for k, v in case["state"].items()
            )
            s = f"(stateOf [{state}])"
            rw = runtime.get("consistent")
            if rw == "no":
                thm(f"{name}_runtime_dead", f"∀ I, ¬ SatIn I {s} {exp}.lits",
                    "runtime_dead (by decide)")
            elif rw == "yes":
                thm(f"{name}_runtime_live", f"∀ I, SatIn I {s} {exp}.lits",
                    "runtime_live (by decide)")
            else:
                ex(f"runtime {reg} {s} {name} = .unknown")
        lines.append("")

    lines.append("end PredicateTheory")
    OUT.write_text("\n".join(lines) + "\n")
    print(
        f"{len(cases)} cases: {counts['theorem']} theorems, {counts['example']} checked examples; "
        f"wrote {OUT.relative_to(HERE)}"
    )


if __name__ == "__main__":
    main()
