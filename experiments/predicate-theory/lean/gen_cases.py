#!/usr/bin/env python3
"""Write PredicateTheory/Generated.lean from ../cases.json.

Every case whose labels are inside the Lean fragment becomes a theorem or a
checked example:

  consistent: no    theorem  ¬ Sat labels            (dead_sound)
  consistent: yes   example  dead labels = false     (the checker agrees)
  entails g: yes    theorem  Entails labels g        (entails_sound)
  entails g: no     example  entails labels g = false

The fragment: num_gt, num_gte, num_lt, num_lte, num_eq (integer constants or
paths), positive amount_in_range, bool_true, bool_false, state_exists,
signed_by. Cases with accepted state, custom declarations, or anything else
are listed at the end of the file as outside the fragment.

Run from this directory: python3 gen_cases.py
"""

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
CASES = HERE.parent / "cases.json"
OUT = HERE / "PredicateTheory" / "Generated.lean"

ORDER = {"num_gt", "num_gte", "num_lt", "num_lte", "num_eq"}
UNARY = {"bool_true", "bool_false", "state_exists", "signed_by"}
LITERAL = re.compile(r"^([+-])(\w+)\((.*)\)$")
INTEGER = re.compile(r"^-?\d+$")


class Outside(Exception):
    pass


def split_args(raw):
    args, cur, quoted = [], "", False
    for ch in raw:
        if ch == '"':
            quoted = not quoted
            cur += ch
        elif ch == "," and not quoted:
            args.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        args.append(cur.strip())
    return args


def path(arg):
    if not arg.startswith("/") or '"' in arg:
        raise Outside(f"not a path: {arg}")
    return f'"{arg}"'


def term(arg):
    if arg.startswith("/"):
        return f'(.path "{arg}")'
    value = arg.strip('"')
    if not INTEGER.match(value):
        raise Outside(f"not an integer constant: {arg}")
    n = int(value)
    return f"(.const {n})" if n >= 0 else f"(.const ({n}))"


def literals(text):
    """One label as a list of Lean literals (amount_in_range gives two)."""
    m = LITERAL.match(text.strip())
    if not m:
        raise Outside(f"not a predicate literal: {text}")
    sign, name, raw = m.groups()
    args = split_args(raw)
    ctor = "pos" if sign == "+" else "neg"
    if name in ORDER and len(args) == 2:
        return [f"{ctor} ({name} {path(args[0])} {term(args[1])})"]
    if name in UNARY and len(args) == 1:
        return [f"{ctor} ({name} {path(args[0])})"]
    if name == "amount_in_range" and len(args) == 3 and sign == "+":
        p = path(args[0])
        return [
            f"pos (num_gte {p} {term(args[1])})",
            f"pos (num_lte {p} {term(args[2])})",
        ]
    raise Outside(f"outside the fragment: {text}")


def labels(texts):
    out = []
    for t in texts:
        out.extend(literals(t))
    return "[" + ", ".join(out) + "]"


def ident(case_id):
    return "case_" + re.sub(r"\W", "_", case_id)


def main():
    cases = json.loads(CASES.read_text())["cases"]
    lines = [
        "import PredicateTheory.Sound",
        "",
        "/-!",
        "Generated by `gen_cases.py` from `../cases.json`. Do not edit.",
        "",
        "Each case inside the Lean fragment, decided by the proven checker. A",
        "`no` is a theorem that no world satisfies the labels; an entailment is",
        "a theorem about every world. A `yes` is an example that the checker",
        "does not call the labels dead.",
        "-/",
        "",
        "namespace PredicateTheory",
        "",
        "-- Composing edges on three-literal sets unfolds deeper than the default.",
        "set_option maxRecDepth 8192",
        "",
    ]
    outside = []
    count = 0
    for case in cases:
        cid = case["id"]
        if case.get("state") or case.get("declarations"):
            outside.append((cid, "accepted state or custom declarations"))
            continue
        try:
            ls = labels(case["literals"])
            v1 = case.get("v1", {})
            body = []
            name = ident(cid)
            if v1.get("consistent") == "no":
                body.append(f"theorem {name} : ¬ Sat ({ls} : List (Lit Int)) :=")
                body.append("  dead_sound (by decide)")
            elif v1.get("consistent") == "yes":
                body.append(f"example : dead ({ls} : List (Lit Int)) = false := by decide")
            for i, (goal, want) in enumerate(sorted(v1.get("entails", {}).items())):
                g = literals(goal)
                if len(g) != 1:
                    raise Outside(f"goal is not one literal: {goal}")
                if want == "yes":
                    body.append(f"theorem {name}_entails_{i} :")
                    body.append(f"    Entails ({ls} : List (Lit Int)) ({g[0]}) :=")
                    body.append("  entails_sound (by decide)")
                elif want == "no":
                    body.append(
                        f"example : entails ({ls} : List (Lit Int)) ({g[0]}) = false := by decide"
                    )
            if not body:
                raise Outside("no yes/no verdict")
        except Outside as why:
            outside.append((cid, str(why)))
            continue
        lines.append(f"/-- {cid}: {case['title']} -/")
        lines.extend(body)
        lines.append("")
        count += 1

    lines.append("/-! Outside the fragment (checked in Rust only):")
    lines.append("")
    for cid, why in outside:
        lines.append(f"- {cid}: {why}")
    lines.append("-/")
    lines.append("")
    lines.append("end PredicateTheory")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{count} cases in the fragment, {len(outside)} outside; wrote {OUT.relative_to(HERE)}")


if __name__ == "__main__":
    main()
